#!/usr/bin/env node
/*
 * Recipe 3 — scan the source tree for Playwright locator calls and emit
 * docs/SELECTORS.md, a flat inventory grouped by module with fragility
 * flags and duplicate detection. Complements (does not replace) the page
 * registry at .cursor/docs/registry.md.
 *
 * Usage:
 *   node scripts/generate-selectors-doc.js
 *
 * Exit codes:
 *   0  — doc generated
 *   1  — no source files found (repo layout changed?)
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const ROOTS = ['src/pages', 'src/components', 'src/actions'];
const OUT = path.join(ROOT, 'docs', 'SELECTORS.md');

// Matches the common Playwright locator APIs. The 'args' group is greedy within
// balanced parens on a single line — good enough for the 98% case; multi-line
// calls are skipped (flagged as 'complex' in output).
const LOC_RE =
  /(getByRole|getByText|getByLabel|getByPlaceholder|getByTestId|getByAltText|getByTitle|locator|page\.\$|page\.\$\$|\$x)\s*\(\s*([^)]*?)\s*\)/g;

function walk(dir, out = []) {
  let entries = [];
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return out;
  }
  for (const e of entries) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (e.isFile() && /\.ts$/.test(e.name)) out.push(p);
  }
  return out;
}

function moduleOf(relPath) {
  const parts = relPath.split(/[\\/]/);
  if (parts[0] !== 'src') return 'other';
  if (parts.length < 3) return parts[1] || 'other';
  return parts[2]; // src/pages/<module>/...
}

function fragilityFlags(kind, rawArg) {
  const arg = rawArg || '';
  const flags = [];
  if (/nth-child|:nth-of-type/.test(arg)) flags.push('nth-child');
  if (/\/\/[A-Za-z]/.test(arg) && /\[\d+\]/.test(arg)) flags.push('positional-xpath');
  if (/^['"`].{40,}['"`]/.test(arg.trim())) flags.push('long-text');
  if (kind === 'locator' && /^['"`]#[A-Za-z_]/.test(arg.trim()) && !/data-/.test(arg))
    flags.push('raw-id-no-attr');
  if (kind === '$x') flags.push('xpath-legacy');
  if (/visible\s*=\s*true/.test(arg)) flags.push('deprecated-visible=true'); // KI-08
  return flags;
}

function relative(p) {
  return path.relative(ROOT, p).replace(/\\/g, '/');
}

function countNewlinesBefore(src, idx) {
  let n = 1;
  for (let i = 0; i < idx; i++) if (src.charCodeAt(i) === 10) n++;
  return n;
}

function scanFile(abs) {
  const src = fs.readFileSync(abs, 'utf8');
  const rows = [];
  LOC_RE.lastIndex = 0;
  let m;
  while ((m = LOC_RE.exec(src)) !== null) {
    const [, kind, rawArg] = m;
    const line = countNewlinesBefore(src, m.index);
    const arg = rawArg.replace(/\s+/g, ' ').trim().slice(0, 160);
    rows.push({
      kind,
      arg,
      flags: fragilityFlags(kind, rawArg),
      file: relative(abs),
      line,
    });
  }
  return rows;
}

// --- scan ---
const files = [];
for (const r of ROOTS) files.push(...walk(path.join(ROOT, r)));

if (files.length === 0) {
  console.error('No .ts files found under', ROOTS.join(', '));
  process.exit(1);
}

const allRows = [];
for (const f of files) allRows.push(...scanFile(f));

// --- group ---
const byModule = new Map();
for (const r of allRows) {
  const mod = moduleOf(r.file);
  if (!byModule.has(mod)) byModule.set(mod, []);
  byModule.get(mod).push(r);
}

// --- dedup detection (same kind+arg in multiple files) ---
const seen = new Map();
for (const r of allRows) {
  const key = `${r.kind}(${r.arg})`;
  if (!seen.has(key)) seen.set(key, []);
  seen.get(key).push(`${r.file}:${r.line}`);
}
const duplicates = new Map();
for (const [k, locs] of seen) {
  if (locs.length > 1) duplicates.set(k, locs);
}

// --- emit ---
function escape(s) {
  return String(s).replace(/\|/g, '\\|');
}

const ts = new Date().toISOString().replace(/\..*/, 'Z');
let md = '';
md += '# Playwright Selector Catalog\n\n';
md += `_Auto-generated by \`scripts/generate-selectors-doc.js\` on ${ts}._\n\n`;
md += '_Do not edit by hand — regenerate with `node scripts/generate-selectors-doc.js`._\n\n';
md += '## Summary\n\n';
md += `- Total locator calls: **${allRows.length}**\n`;
md += `- Files scanned: ${files.length}\n`;
md += `- Modules: ${[...byModule.keys()].sort().join(', ')}\n`;
md += `- Duplicate selectors (same kind + arg in 2+ places): **${duplicates.size}**\n`;
md += `- Fragility flags: nth-child, positional-xpath, long-text, raw-id-no-attr, xpath-legacy, deprecated-visible=true (KI-08)\n\n`;

md += '## Fragile selectors (sorted by severity)\n\n';
const fragile = allRows
  .filter((r) => r.flags.length > 0)
  .sort((a, b) => b.flags.length - a.flags.length);
if (fragile.length === 0) {
  md += '_None found._\n\n';
} else {
  md += '| File:Line | Kind | Selector | Flags |\n';
  md += '|-----------|------|----------|-------|\n';
  for (const r of fragile) {
    md += `| ${escape(r.file)}:${r.line} | ${r.kind} | \`${escape(r.arg)}\` | ${r.flags.join(', ')} |\n`;
  }
  md += '\n';
}

md += '## Duplicate selectors (candidates for shared helpers)\n\n';
if (duplicates.size === 0) {
  md += '_None found._\n\n';
} else {
  md += '| Selector | Occurrences |\n';
  md += '|----------|-------------|\n';
  for (const [sel, locs] of [...duplicates.entries()].sort((a, b) => b[1].length - a[1].length)) {
    md += `| \`${escape(sel)}\` | ${locs.map((l) => escape(l)).join('<br>')} |\n`;
  }
  md += '\n';
}

md += '## Full inventory by module\n\n';
for (const mod of [...byModule.keys()].sort()) {
  const rows = byModule.get(mod);
  md += `### ${mod} (${rows.length})\n\n`;
  md += '| File:Line | Kind | Selector | Flags |\n';
  md += '|-----------|------|----------|-------|\n';
  for (const r of rows) {
    md += `| ${escape(r.file)}:${r.line} | ${r.kind} | \`${escape(r.arg)}\` | ${r.flags.join(', ') || '-'} |\n`;
  }
  md += '\n';
}

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, md);
console.log(`Wrote ${relative(OUT)} — ${allRows.length} locator calls, ${fragile.length} flagged, ${duplicates.size} duplicates.`);
